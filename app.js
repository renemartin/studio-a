let lang = localStorage.getItem("studio-a-lang") || "es";

function applyLang() {
  document.documentElement.lang = lang;
  document.querySelectorAll("[data-i]").forEach((el) => {
    const key = el.getAttribute("data-i");
    if (i18n[lang][key]) el.textContent = i18n[lang][key];
  });
  document.querySelectorAll("[data-i-placeholder]").forEach((el) => {
    const key = el.getAttribute("data-i-placeholder");
    if (i18n[lang][key]) el.setAttribute("placeholder", i18n[lang][key]);
  });
  document.querySelectorAll(".lang button").forEach((b) => {
    b.classList.toggle("active", b.dataset.lang === lang);
  });
  localStorage.setItem("studio-a-lang", lang);
}

document.querySelectorAll(".lang button").forEach((b) => {
  b.addEventListener("click", () => {
    lang = b.dataset.lang;
    applyLang();
  });
});

window.addEventListener("scroll", () => {
  document.querySelector(".nav").classList.toggle("is-scrolled", window.scrollY > 8);
});

const lightbox = document.getElementById("lightbox");
const lightboxImg = lightbox.querySelector("img");

document.querySelectorAll(".tile").forEach((tile) => {
  tile.addEventListener("click", () => {
    lightboxImg.src = tile.querySelector("img").src;
    lightboxImg.alt = tile.querySelector("img").alt;
    lightbox.classList.add("open");
  });
});

lightbox.addEventListener("click", (e) => {
  if (e.target === lightbox || e.target.tagName === "BUTTON") {
    lightbox.classList.remove("open");
    lightboxImg.src = "";
  }
});

document.addEventListener("keydown", (e) => {
  if (e.key === "Escape") lightbox.classList.remove("open");
});

const fileInput = document.getElementById("photos");
const uploads = document.getElementById("uploads");

fileInput.addEventListener("change", () => {
  [...fileInput.files].slice(0, 4).forEach((file) => {
    const url = URL.createObjectURL(file);
    const box = document.createElement("div");
    box.className = "drop";
    const img = document.createElement("img");
    img.src = url;
    img.alt = file.name;
    box.appendChild(img);
    uploads.insertBefore(box, uploads.firstChild);
  });
});

document.getElementById("commission-form").addEventListener("submit", (e) => {
  e.preventDefault();
  e.currentTarget.classList.add("sent");
});

